import { bundle, bundleCall, ROOT, seed, openPage, sleep, type, click } from './harness.mjs';
let pass = 0, fail = 0;
const ok = (c, n, x = '') => { c ? pass++ : fail++; console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : '  ' + x)); };
const code = await bundle('js/profile.js');
const db = seed(); db.profiles[0].username = 'amr'; db.profiles[1].username = 'taken_name';
const U1 = { id: 'U1' };
let p = await openPage('profile.html', '', db, U1, code); await sleep(300);
const d = p.doc, w = p.w;
ok(!d.getElementById('profile-form').hidden && d.getElementById('username').value === 'amr', 'P1 profile loads into the form');
const submit = () => d.getElementById('profile-form').dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
type(w, d.getElementById('full_name'), ''); submit(); await sleep(100);
ok(d.getElementById('full_name-error').textContent.includes('required') && db.profiles[0].full_name === '', 'P2 empty name is rejected and nothing is written');
type(w, d.getElementById('full_name'), 'Amr Ahmed'); type(w, d.getElementById('username'), 'a!'); submit(); await sleep(100);
ok(d.getElementById('username-error').textContent.length > 0, 'P3 invalid username rejected');
type(w, d.getElementById('username'), 'taken_name'); submit(); await sleep(150);
ok(/already taken/.test(d.getElementById('username-error').textContent) && db.profiles[0].username === 'amr' && !db.profiles[0].full_name, 'P4 duplicate username is reported and nothing is saved');
type(w, d.getElementById('username'), 'amr_dev'); type(w, d.getElementById('website'), 'amr.dev'); type(w, d.getElementById('title'), 'Frontend Developer'); submit(); await sleep(200);
ok(db.profiles[0].full_name === 'Amr Ahmed' && db.profiles[0].username === 'amr_dev' && db.profiles[0].website === 'https://amr.dev' && db.profiles[0].title === 'Frontend Developer', 'P5 valid save persists', JSON.stringify(db.profiles[0]));
p = await openPage('profile.html', '', db, U1, code); await sleep(300);
ok(p.doc.getElementById('full_name').value === 'Amr Ahmed', 'P6 data persists after refresh');
ok(db.profiles[1].full_name === 'Other', 'P7 other users\' profiles untouched');
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
