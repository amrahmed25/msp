var audioCtx;

function initAudio() {

    if (!audioCtx) {
        audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    }

    if (audioCtx.state === "suspended") {
        audioCtx.resume();
    }
}


function playSound(type) {
    try {
        initAudio();

        if (!audioCtx) return;

        var now = audioCtx.currentTime;

       
        if (type === "correct") {

            var notes = [659.25, 987.77];
            var noteLength = 0.12;

            for (var n = 0; n < notes.length; n++) {

                var osc = audioCtx.createOscillator();
                var gain = audioCtx.createGain();

                osc.connect(gain);
                gain.connect(audioCtx.destination);

                osc.type = "sine";
                osc.frequency.setValueAtTime(notes[n], now + n * noteLength);

                gain.gain.setValueAtTime(0.0001, now + n * noteLength);
                gain.gain.linearRampToValueAtTime(0.22, now + n * noteLength + 0.015);
                gain.gain.exponentialRampToValueAtTime(0.001, now + n * noteLength + noteLength);

                osc.start(now + n * noteLength);
                osc.stop(now + n * noteLength + noteLength);
            }
        }
       
        else if (type === "wrong") {

            var osc = audioCtx.createOscillator();
            var gain = audioCtx.createGain();

            osc.connect(gain);
            gain.connect(audioCtx.destination);

            osc.type = "triangle";

            osc.frequency.setValueAtTime(311.13, now);
            osc.frequency.exponentialRampToValueAtTime(196.00, now + 0.3);

            gain.gain.setValueAtTime(0.0001, now);
            gain.gain.linearRampToValueAtTime(0.2, now + 0.02);
            gain.gain.exponentialRampToValueAtTime(0.001, now + 0.35);

            osc.start(now);
            osc.stop(now + 0.35);
        }


       
        else if (type === "tick") {

            var osc = audioCtx.createOscillator();
            var gain = audioCtx.createGain();

            osc.connect(gain);
            gain.connect(audioCtx.destination);

            osc.type = "square";

            osc.frequency.setValueAtTime(850, now);

            gain.gain.setValueAtTime(0.12, now);
            gain.gain.exponentialRampToValueAtTime(0.01, now + 0.08);

            osc.start(now);
            osc.stop(now + 0.08);
        }

            else if (type === "gameover") {

            var notes = [659.25, 523.25, 392.00, 261.63];
            var noteLength = 0.18;

            for (var n = 0; n < notes.length; n++) {

                var osc = audioCtx.createOscillator();
                var gain = audioCtx.createGain();

                osc.connect(gain);
                gain.connect(audioCtx.destination);

                osc.type = "triangle";

                osc.frequency.setValueAtTime(
                    notes[n],
                    now + n * noteLength
                );

                gain.gain.setValueAtTime(
                    0.0001,
                    now + n * noteLength
                );

                gain.gain.linearRampToValueAtTime(
                    0.25,
                    now + n * noteLength + 0.02
                );

                gain.gain.exponentialRampToValueAtTime(
                    0.001,
                    now + n * noteLength + noteLength + 0.12
                );

                osc.start(now + n * noteLength);

                osc.stop(
                    now + n * noteLength + noteLength + 0.12
                );
            }
        }
    }
    catch (error) {
        console.log("Sound error:", error);
    }
}


function shuffle(array) {
    var newArray = array.slice();

    for (var i = newArray.length - 1; i > 0; i--) {
        var randomIndex = Math.floor(Math.random() * (i + 1));

        var temp = newArray[i];
        newArray[i] = newArray[randomIndex];
        newArray[randomIndex] = temp;
    }

    return newArray;
}


